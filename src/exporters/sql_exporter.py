"""
SQL Exporter for LotTrace AI.
Generates ANSI SQL insert dumps for all operational tables into data/generated/sql/.
"""

from pathlib import Path
from typing import Dict, Any
from config import SQL_EXPORT_DIR
from src.database.connection import get_db_session, Base
from src.utils.logging_config import logger


class SQLExporter:
    """Exports all entities to individual SQL INSERT script files."""

    def __init__(self, output_dir: Path = SQL_EXPORT_DIR):
        self.output_dir = output_dir
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def export_all(self) -> Dict[str, int]:
        """Dumps all tables to SQL insert files. Returns dict of table_name -> row_count."""
        logger.info(f"Exporting all database tables to SQL at {self.output_dir}...")
        counts = {}
        master_dump_path = self.output_dir / "lottrace_dump.sql"

        with open(master_dump_path, "w", encoding="utf-8") as master_f:
            master_f.write("-- LotTrace AI ANSI SQL Database Dump\n")
            master_f.write("-- Generated by LotTrace AI Exporter\n\n")

            with get_db_session() as session:
                for mapper in Base.registry.mappers:
                    model_cls = mapper.class_
                    table_name = model_cls.__tablename__
                    table_file_path = self.output_dir / f"{table_name}.sql"

                    records = session.query(model_cls).all()
                    rows = [r.to_dict() for r in records if hasattr(r, "to_dict")]

                    with open(table_file_path, "w", encoding="utf-8") as tf:
                        tf.write(f"-- Table: {table_name}\n")
                        master_f.write(f"-- Table: {table_name}\n")

                        for row in rows:
                            cols = []
                            vals = []
                            for k, v in row.items():
                                cols.append(f'"{k}"')
                                if v is None:
                                    vals.append("NULL")
                                elif isinstance(v, (int, float)):
                                    vals.append(str(v))
                                elif isinstance(v, bool):
                                    vals.append("1" if v else "0")
                                else:
                                    escaped = str(v).replace("'", "''")
                                    vals.append(f"'{escaped}'")

                            stmt = f"INSERT INTO {table_name} ({', '.join(cols)}) VALUES ({', '.join(vals)});\n"
                            tf.write(stmt)
                            master_f.write(stmt)

                    counts[table_name] = len(rows)
                    master_f.write("\n")

        logger.info(f"SQL export complete: {len(counts)} tables written to {master_dump_path}.")
        return counts
